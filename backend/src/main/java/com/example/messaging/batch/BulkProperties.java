package com.example.messaging.batch;

import java.time.Duration;
import org.springframework.boot.context.properties.ConfigurationProperties;
import org.springframework.boot.context.properties.bind.DefaultValue;

/**
 * Additional {@code messaging.bulk.*} keys owned by the batch module. The core keys
 * ({@code concurrency, chunk-size, skip-limit, max-rows, upload-dir}) stay in
 * {@link com.example.messaging.config.MessagingProperties.Bulk}; this record only adds knobs that have safe defaults,
 * so no change to the shared {@code application*.yml} is required.
 */
@ConfigurationProperties("messaging.bulk")
public record BulkProperties(
        /** Hard cap for an uploaded CSV (bytes); larger uploads are refused with 413. */
        @DefaultValue("20971520") long maxUploadBytes,
        /** Longest accepted CSV line (characters). */
        @DefaultValue("8192") int maxLineLength,
        /** Most columns a header may declare. */
        @DefaultValue("51") int maxColumns,
        /** Rate applied when a request does not give one; 0 = unlimited (the provider token bucket still applies). */
        @DefaultValue("0") int defaultRatePerSecond,
        /** Upper bound of {@code ratePerSecond} a client may request. */
        @DefaultValue("10000") int maxRatePerSecond,
        /** Retry attempts for transient database errors inside a chunk. */
        @DefaultValue("3") int retryLimit,
        /** Rows generated by {@code generate-synthetic} never exceed this (nor {@code max-rows}). */
        @DefaultValue("100000") int maxSyntheticRows,
        /** Number of bulk jobs that may run at the same time (each one uses {@code concurrency} worker threads). */
        @DefaultValue("2") int maxParallelJobs,
        /** How many launched-but-not-yet-running jobs may wait; beyond it creating a job returns 503. */
        @DefaultValue("20") int launchQueueCapacity,
        /** RUNNING/CREATED jobs without progress for this long are marked ABANDONED by the sweeper. */
        @DefaultValue("30m") Duration staleAfter,
        /** Sweeper period. */
        @DefaultValue("60s") Duration sweepInterval,
        /** How long {@code stop} waits for the current chunk to finish before answering. */
        @DefaultValue("10s") Duration stopWait,
        /** When false the sweeper does not run (tests). */
        @DefaultValue("true") boolean sweeperEnabled,
        /**
         * Delete the uploaded CSV as soon as the job ended COMPLETED / COMPLETED_WITH_ERRORS (data minimisation: the file
         * holds recipient references and message variables). FAILED / STOPPED jobs keep it, a restart needs it; the
         * retention job removes what is left after {@code messaging.retention.message-days}.
         */
        @DefaultValue("true") boolean deleteFileOnCompletion) {}
