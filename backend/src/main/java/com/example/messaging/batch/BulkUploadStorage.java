package com.example.messaging.batch;

import com.example.messaging.common.ApiException;
import com.example.messaging.common.ErrorCode;
import com.example.messaging.config.MessagingProperties;
import java.io.BufferedWriter;
import java.io.FilterInputStream;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.io.UncheckedIOException;
import java.nio.charset.CharacterCodingException;
import java.nio.charset.CodingErrorAction;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardOpenOption;
import java.util.List;
import java.util.Locale;
import java.util.Set;
import java.util.regex.Pattern;
import org.springframework.batch.item.file.transform.DelimitedLineTokenizer;
import org.springframework.stereotype.Component;

/**
 * Receives bulk CSV files. The upload is streamed (never held in memory), re-encoded as plain UTF-8 with {@code \n}
 * line ends while it is validated, and written to {@code <upload-dir>/<tenant>/<jobId>.csv}.
 *
 * <p>Safety rules: the stored name is generated by the server (the client file name is only sanitised for display),
 * the tenant directory name is validated, every path is normalised and must stay inside the upload directory, the
 * byte and row limits are enforced while streaming, the content must be strict UTF-8, no line may exceed the line
 * limit, the header must be valid, and the partial file is deleted on any failure.
 */
@Component
public class BulkUploadStorage {

    private static final Pattern TENANT = Pattern.compile("[A-Za-z0-9_-]{1,64}");
    private static final Pattern JOB_FILE = Pattern.compile("[0-9a-fA-F-]{36}\\.csv");
    private static final Set<String> ACCEPTED_TYPES = Set.of("text/csv", "application/csv", "text/plain",
            "application/vnd.ms-excel", "application/octet-stream");

    /** Result of a successful {@link #store}. */
    public record StoredUpload(Path path, String displayName, long rows, long bytes) {}

    private final Path baseDir;
    private final BulkProperties bulk;
    private final int maxRows;

    public BulkUploadStorage(MessagingProperties props, BulkProperties bulk) {
        this.baseDir = Path.of(props.bulk().uploadDir()).toAbsolutePath().normalize();
        this.bulk = bulk;
        this.maxRows = props.bulk().maxRows();
    }

    public int maxRows() {
        return maxRows;
    }

    public Path baseDir() {
        return baseDir;
    }

    // ------------------------------------------------------------------ paths

    private Path tenantDir(String tenantId) {
        if (tenantId == null || !TENANT.matcher(tenantId).matches()) {
            throw new ApiException.ValidationException("tenant", "Invalid tenant id");
        }
        return requireInsideUploadDir(baseDir.resolve(tenantId));
    }

    /** Reserves the (not yet existing) target file of a job, e.g. for the synthetic generator. */
    public Path newJobFile(String tenantId, String jobId) throws IOException {
        if (!JOB_FILE.matcher(jobId + ".csv").matches()) {
            throw new IllegalArgumentException("invalid job id");
        }
        Path dir = tenantDir(tenantId);
        Files.createDirectories(dir);
        return requireInsideUploadDir(dir.resolve(jobId + ".csv"));
    }

    /** @throws IllegalArgumentException when {@code p} escapes the upload directory (path traversal guard) */
    public Path requireInsideUploadDir(Path p) {
        Path n = p.toAbsolutePath().normalize();
        if (!n.startsWith(baseDir)) {
            throw new IllegalArgumentException("path is outside the bulk upload directory");
        }
        return n;
    }

    public void deleteQuietly(Path p) {
        try {
            if (p != null) {
                Files.deleteIfExists(requireInsideUploadDir(p));
            }
        } catch (IOException | RuntimeException ignored) {
            // best effort
        }
    }

    // ------------------------------------------------------------------ names and types

    /** Display-only name: base name, printable ASCII subset, bounded, always ending in .csv. */
    public static String sanitizeFileName(String original) {
        String name = original == null ? "" : original;
        int slash = Math.max(name.lastIndexOf('/'), name.lastIndexOf('\\'));
        if (slash >= 0) {
            name = name.substring(slash + 1);
        }
        name = name.replaceAll("[^A-Za-z0-9._ -]", "_").replaceAll("\\.{2,}", ".").trim();
        if (name.length() > 100) {
            name = name.substring(name.length() - 100);
        }
        if (name.isEmpty() || name.equals(".") || name.startsWith(".")) {
            name = "upload" + name;
        }
        if (!name.toLowerCase(Locale.ROOT).endsWith(".csv")) {
            name = name + ".csv";
        }
        return name;
    }

    static void checkContentType(String contentType, String originalName) {
        if (originalName != null && !originalName.isBlank()
                && !originalName.toLowerCase(Locale.ROOT).endsWith(".csv")) {
            throw new ApiException.ValidationException("file", "only .csv files are accepted");
        }
        if (contentType != null && !contentType.isBlank()) {
            String base = contentType.toLowerCase(Locale.ROOT).split(";")[0].trim();
            if (!ACCEPTED_TYPES.contains(base)) {
                throw new ApiException.ValidationException("file", "unsupported content type; send text/csv");
            }
        }
    }

    // ------------------------------------------------------------------ store

    public StoredUpload store(String tenantId, String jobId, InputStream in, String originalName, String contentType) {
        checkContentType(contentType, originalName);
        Path target;
        try {
            target = newJobFile(tenantId, jobId);
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
        long rows = 0;
        long bytes;
        try {
            CountingInputStream counted = new CountingInputStream(in, bulk.maxUploadBytes());
            var decoder = StandardCharsets.UTF_8.newDecoder().onMalformedInput(CodingErrorAction.REPORT)
                    .onUnmappableCharacter(CodingErrorAction.REPORT);
            try (BoundedLineReader lines = new BoundedLineReader(new InputStreamReader(counted, decoder),
                    bulk.maxLineLength());
                    BufferedWriter out = Files.newBufferedWriter(target, StandardCharsets.UTF_8,
                            StandardOpenOption.CREATE_NEW, StandardOpenOption.WRITE)) {
                String header = lines.readLine();
                if (header == null || header.isBlank()) {
                    throw new ApiException.ValidationException("file", "the file is empty");
                }
                if (BoundedLineReader.TOO_LONG.equals(header)) {
                    throw new ApiException.ValidationException("file", "the header line is too long");
                }
                header = CsvRowValidator.stripBom(header);
                validateHeader(header);
                out.write(header);
                out.write('\n');
                long lineNo = 1;
                long pendingBlank = 0;
                String line;
                while ((line = lines.readLine()) != null) {
                    lineNo++;
                    if (BoundedLineReader.TOO_LONG.equals(line)) {
                        throw new ApiException.ValidationException("file", "line " + lineNo + " is longer than "
                                + bulk.maxLineLength() + " characters");
                    }
                    if (line.isBlank()) {
                        pendingBlank++; // trailing blank lines are dropped, interior ones are reported by the job
                        continue;
                    }
                    for (; pendingBlank > 0; pendingBlank--) {
                        out.write('\n');
                    }
                    out.write(line);
                    out.write('\n');
                    if (++rows > maxRows) {
                        throw new ApiException(ErrorCode.PAYLOAD_TOO_LARGE, "the file has more than " + maxRows
                                + " data rows (messaging.bulk.max-rows)");
                    }
                }
            }
            bytes = counted.count();
            if (rows == 0) {
                throw new ApiException.ValidationException("file", "the file has a header but no data rows");
            }
        } catch (java.nio.file.FileAlreadyExistsException e) {
            throw new UncheckedIOException(e); // not our file: never delete it
        } catch (CharacterCodingException e) {
            deleteQuietly(target);
            throw new ApiException.ValidationException("file", "the file is not valid UTF-8");
        } catch (TooLargeException e) {
            deleteQuietly(target);
            throw new ApiException(ErrorCode.PAYLOAD_TOO_LARGE,
                    "the file is larger than " + bulk.maxUploadBytes() + " bytes");
        } catch (IOException e) {
            deleteQuietly(target);
            throw new UncheckedIOException(e);
        } catch (RuntimeException e) {
            deleteQuietly(target);
            throw e;
        }
        return new StoredUpload(target, sanitizeFileName(originalName), rows, bytes);
    }

    private void validateHeader(String header) {
        try {
            DelimitedLineTokenizer t = RecipientCsvReaderFactory.newTokenizer();
            t.setStrict(false);
            List<String> cols = List.of(t.tokenize(header).getValues());
            CsvRowValidator.validateHeader(cols, bulk.maxColumns());
        } catch (BulkRowException e) {
            throw new ApiException.ValidationException("file", e.getMessage());
        } catch (RuntimeException e) {
            throw new ApiException.ValidationException("file", "the header line is not valid CSV");
        }
    }

    /** Signals that the upload exceeded the byte limit. */
    static final class TooLargeException extends IOException {
        private static final long serialVersionUID = 1L;

        TooLargeException() {
            super("upload too large");
        }
    }

    private static final class CountingInputStream extends FilterInputStream {
        private final long max;
        private long count;

        CountingInputStream(InputStream in, long max) {
            super(in);
            this.max = max;
        }

        long count() {
            return count;
        }

        @Override
        public int read() throws IOException {
            int b = super.read();
            if (b >= 0 && ++count > max) {
                throw new TooLargeException();
            }
            return b;
        }

        @Override
        public int read(byte[] buf, int off, int len) throws IOException {
            int n = super.read(buf, off, len);
            if (n > 0) {
                count += n;
                if (count > max) {
                    throw new TooLargeException();
                }
            }
            return n;
        }
    }
}
